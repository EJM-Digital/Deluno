/**
 * Every surface Deluno exposes, and whether anything tests it.
 *
 * The product owner's bar is that nothing is left untested. That is a claim
 * nobody can check by reading a test list, so this counts instead: it
 * enumerates every API route and every owner-reachable screen straight from
 * the source, looks for something that exercises each one, and reports what is
 * left over.
 *
 * The pattern is borrowed from GuideCapabilityInventory, which accounts for all
 * 85 TRaSH formats and gates the write path on zero unaccounted. That is what
 * turned "we handled the guide properly" from an assertion into a number, and
 * this is the same move applied to the product.
 *
 * It is deliberately blunt about what counts as coverage: a route is covered if
 * its path appears in a test. That over-counts - a mention is not an assertion -
 * so treat the covered number as the ceiling and the uncovered number as the
 * one that matters. An uncovered surface is definitely untested; a covered one
 * is only probably tested.
 *
 *   node scripts/coverage-inventory.mjs           # write docs/coverage-inventory.md
 *   node scripts/coverage-inventory.mjs --check   # non-zero exit if anything is uncovered
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

/** Every file under a directory whose name matches, read once. */
function readAll(dir, pattern) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "bin" || entry.name === "obj" || entry.name === "node_modules") continue;
      out.push(...readAll(full, pattern));
    } else if (pattern.test(entry.name)) {
      out.push({ path: full, text: fs.readFileSync(full, "utf8") });
    }
  }
  return out;
}

// ---------------------------------------------------------------- API routes
// From the snapshot the routing tests already maintain, so this cannot drift
// from what the application actually maps.
const snapshotPath = path.join(root, "tests/Deluno.Platform.Tests/Routing/endpoint-inventory.snapshot.txt");
const apiRoutes = fs
  .readFileSync(snapshotPath, "utf8")
  .split("\n")
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const [method, ...rest] = line.split(" ");
    return rest.length ? { method, route: rest.join(" ") } : { method: "ANY", route: method };
  })
  // Hubs are SignalR negotiation paths rather than things an owner calls.
  .filter((entry) => !entry.route.startsWith("/hubs/"));

// ---------------------------------------------------------------- web routes
// Nested `path:` segments joined into the URL an owner actually visits.
const routerText = fs.readFileSync(path.join(root, "apps/web/src/router.tsx"), "utf8");
const webRoutes = [...routerText.matchAll(/path:\s*"([^"]*)"/g)]
  .map((match) => match[1])
  .filter((value) => value !== "" && !value.includes(":") && value !== "*")
  .map((value) => (value.startsWith("/") ? value : `/${value}`));

// ------------------------------------------------------------------- corpora
const backendTests = readAll(path.join(root, "tests"), /\.cs$/).map((file) => file.text).join("\n");
const webTests = readAll(path.join(root, "apps/web/tests"), /\.(ts|tsx)$/).map((file) => file.text).join("\n");
const webUnitTests = readAll(path.join(root, "apps/web/src"), /\.test\.(ts|tsx)$/).map((file) => file.text).join("\n");
const allTests = `${backendTests}\n${webTests}\n${webUnitTests}`;

/**
 * A route counts as touched when its literal path appears in a test. Route
 * parameters are reduced to a prefix, because a test naming a concrete id is
 * exercising the same endpoint.
 */
function touched(route) {
  const literal = route.split("{")[0].replace(/\/$/, "");
  return literal.length > 4 && allTests.includes(literal);
}

const apiCovered = apiRoutes.filter((entry) => touched(entry.route));
const apiUncovered = apiRoutes.filter((entry) => !touched(entry.route));
const webCovered = webRoutes.filter((route) => touched(route));
const webUncovered = webRoutes.filter((route) => !touched(route));

const lines = [];
lines.push("# Coverage inventory");
lines.push("");
lines.push(`Generated by \`node scripts/coverage-inventory.mjs\` on ${new Date().toISOString().slice(0, 10)}.`);
lines.push("");
lines.push("Every API route and owner-reachable screen, and whether any test mentions it.");
lines.push("");
lines.push("**Read the uncovered number, not the covered one.** A route counts as covered");
lines.push("when its path appears anywhere in a test, which over-counts: a mention is not");
lines.push("an assertion. So covered is a ceiling and uncovered is the floor — an uncovered");
lines.push("surface is definitely untested, a covered one is only probably tested.");
lines.push("");
lines.push("| Surface | Total | Touched by a test | Untouched |");
lines.push("| --- | ---: | ---: | ---: |");
lines.push(`| API routes | ${apiRoutes.length} | ${apiCovered.length} | **${apiUncovered.length}** |`);
lines.push(`| Web screens | ${webRoutes.length} | ${webCovered.length} | **${webUncovered.length}** |`);
lines.push("");
lines.push("## API routes no test mentions");
lines.push("");
if (apiUncovered.length === 0) {
  lines.push("None.");
} else {
  lines.push("| Method | Route |");
  lines.push("| --- | --- |");
  for (const entry of apiUncovered) lines.push(`| ${entry.method} | \`${entry.route}\` |`);
}
lines.push("");
lines.push("## Screens no test visits");
lines.push("");
if (webUncovered.length === 0) {
  lines.push("None.");
} else {
  for (const route of [...new Set(webUncovered)].sort()) lines.push(`- \`${route}\``);
}
lines.push("");

const outputPath = path.join(root, "docs/coverage-inventory.md");
fs.writeFileSync(outputPath, lines.join("\n"), "utf8");

console.log(`API routes   ${apiRoutes.length} total, ${apiUncovered.length} untouched`);
console.log(`Web screens  ${webRoutes.length} total, ${webUncovered.length} untouched`);
console.log(`Written to   ${path.relative(root, outputPath)}`);

if (check && (apiUncovered.length > 0 || webUncovered.length > 0)) {
  console.error(`\n${apiUncovered.length + webUncovered.length} surface(s) no test touches.`);
  process.exit(1);
}
