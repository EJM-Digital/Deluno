import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { areaFor, summarize, renderTable, renderGaps, spliceTable } from "./coverage-docs.mjs";

const CR = String.fromCharCode(13);
const areas = {
  "src/Deluno.Api": { issue: 1297, closes: "a route test" },
  scripts: { issue: 1268, closes: "a node test" },
  "sdk/typescript": { issue: 1268, closes: "a node test" }
};
const baseline = {
  files: {
    "src/Deluno.Api/A.cs": { line: 100, branch: 100 },
    "src/Deluno.Api/B.cs": { line: 90, branch: null },
    "src/Deluno.Api/C.cs": { line: 100, branch: 50 },
    "scripts/x.mjs": { line: 100, branch: 100 },
    "sdk/typescript/src/y.ts": { line: 100, branch: 100 }
  }
};

test("areas follow the folder, with the sdk under its own name", () => {
  assert.equal(areaFor("src/Deluno.Api/A.cs"), "src/Deluno.Api");
  assert.equal(areaFor("scripts/x.mjs"), "scripts");
  assert.equal(areaFor("sdk/typescript/src/y.ts"), "sdk/typescript");
});

test("the table counts files, full files and averages per area", () => {
  const t = renderTable(baseline, areas);
  assert.match(t, /\| src\/Deluno\.Api \| 3 \| 1 \| 2 \| 96\.7% \| 75\.0% \| #1297 \|/);
  assert.match(t, /\| scripts \| 1 \| 1 \| 0 \| 100\.0% \| 100\.0% \| none \|/);
  assert.match(t, /\| \*\*All\*\* \| 5 \| 3 \| 2 \|/);
});

test("every file below 100 is listed with its issue and no full file is", () => {
  const g = renderGaps(baseline, areas);
  assert.match(g, /## src\/Deluno\.Api: 2 of 3 files/);
  assert.match(g, /Issue #1297/);
  assert.match(g, /\| src\/Deluno\.Api\/B\.cs \| 90\.0% \| n\/a \|/);
  assert.match(g, /\| src\/Deluno\.Api\/C\.cs \| 100\.0% \| 50\.0% \|/);
  assert.doesNotMatch(g, /A\.cs/);
  assert.doesNotMatch(g, /## scripts/);
});

test("a file in an area with no issue is reported", () => {
  const { problems } = summarize({ files: { "src/Deluno.New/Z.cs": { line: 1, branch: 1 } } }, areas);
  assert.equal(problems.length, 1);
});

test("the table replaces only what is between the markers", () => {
  const doc = "before\n<!-- coverage-table:start (generated by scripts/coverage/coverage-docs.mjs; do not edit) -->\nold\n<!-- coverage-table:end -->\nafter\n";
  const out = spliceTable(doc, "NEW");
  assert.match(out, /^before\n/);
  assert.match(out, /\nNEW\n\n<!-- coverage-table:end -->\nafter\n$/);
  assert.doesNotMatch(out, /old/);
  assert.throws(() => spliceTable("no markers", "x"));
});

test("the checked-in pages match the checked-in baseline", () => {
  const read = (p) => readFileSync(new URL(`../../docs/testing/${p}`, import.meta.url), "utf8").split(CR).join("");
  const b = JSON.parse(read("coverage-baseline.json"));
  const a = JSON.parse(read("coverage-areas.json")).areas;
  assert.equal(summarize(b, a).problems.length, 0);
  assert.equal(read("coverage-gaps.md"), renderGaps(b, a));
  assert.equal(read("COVERAGE.md"), spliceTable(read("COVERAGE.md"), renderTable(b, a)));
});
