#!/usr/bin/env node
// Keeps the measured-coverage pages in step with the baseline (issue 1268).
//
//   node scripts/coverage/coverage-docs.mjs           check: fail when the pages differ from what the baseline says
//   node scripts/coverage/coverage-docs.mjs --write   rewrite the pages from the baseline
//
// Reads docs/testing/coverage-baseline.json (per file, line and branch percent) and docs/testing/coverage-areas.json (the open
// issue that closes each area). Writes:
//   - the per-area table between the coverage-table markers in docs/testing/COVERAGE.md
//   - docs/testing/coverage-gaps.md: every file below 100% line or branch, with the issue that closes it
// A file in the baseline whose area has no issue in coverage-areas.json fails the check, so no file goes unaccounted for.
// When CI proposes a raised baseline and the owner commits it, run this with --write in the same commit.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { areaOf } from "./merge-coverage.mjs";

const CR = String.fromCharCode(13);
const START = "<!-- coverage-table:start (generated by scripts/coverage/coverage-docs.mjs; do not edit) -->";
const END = "<!-- coverage-table:end -->";

const show = (n) => (n === null || n === undefined ? "n/a" : `${n.toFixed(1)}%`);
const isFull = (v) => v === null || v === undefined || v >= 100;

export function areaFor(file) {
  if (file.startsWith("sdk/typescript/")) return "sdk/typescript";
  return areaOf(file);
}

export function summarize(baseline, areas) {
  const rows = new Map();
  const problems = [];
  for (const [file, v] of Object.entries(baseline.files ?? {})) {
    const area = areaFor(file);
    if (!areas[area]) problems.push(`${file} is in area ${area}, which coverage-areas.json gives no issue.`);
    const r = rows.get(area) ?? { files: 0, full: 0, line: [], branch: [], below: [] };
    r.files += 1;
    if (v.line !== null && v.line !== undefined) r.line.push(v.line);
    if (v.branch !== null && v.branch !== undefined) r.branch.push(v.branch);
    if (isFull(v.line) && isFull(v.branch)) r.full += 1;
    else r.below.push({ file, line: v.line ?? null, branch: v.branch ?? null });
    rows.set(area, r);
  }
  return { rows, problems };
}

const avg = (xs) => (xs.length === 0 ? null : xs.reduce((s, x) => s + x, 0) / xs.length);

export function renderTable(baseline, areas) {
  const { rows } = summarize(baseline, areas);
  const out = [
    "| Area | Files | At 100% line and branch | Below | Average line | Average branch | Issue |",
    "| --- | ---: | ---: | ---: | ---: | ---: | --- |"
  ];
  let files = 0;
  let full = 0;
  const allLine = [];
  const allBranch = [];
  for (const area of [...rows.keys()].sort()) {
    const r = rows.get(area);
    files += r.files;
    full += r.full;
    allLine.push(...r.line);
    allBranch.push(...r.branch);
    const issue = areas[area]?.issue;
    out.push(`| ${area} | ${r.files} | ${r.full} | ${r.below.length} | ${show(avg(r.line))} | ${show(avg(r.branch))} | ${r.below.length === 0 ? "none" : `#${issue}`} |`);
  }
  out.push(`| **All** | ${files} | ${full} | ${files - full} | ${show(avg(allLine))} | ${show(avg(allBranch))} | |`, "");
  out.push("Averages are per file, from the checked-in baseline (the floor the ratchet holds each file to), not weighted by size.");
  return out.join("\n");
}

export function renderGaps(baseline, areas) {
  const { rows } = summarize(baseline, areas);
  const out = [
    "# Files below 100% line or branch coverage",
    "",
    "Generated by `node scripts/coverage/coverage-docs.mjs --write` from `coverage-baseline.json` and `coverage-areas.json`; do not edit.",
    "`node scripts/coverage/coverage-docs.mjs` (run by `npm run ci:check`) fails when this page is out of date, so a file that reaches",
    "100% must leave the list in the commit that raises the baseline, and a file below 100% cannot be missing from it.",
    "Each file's reason is the same: a line or branch no test runs yet. The issue is the open coverage issue of its area that closes it",
    "(`coverage-areas.json`); the line under each area says what test closes its files.",
    ""
  ];
  for (const area of [...rows.keys()].sort()) {
    const r = rows.get(area);
    if (r.below.length === 0) continue;
    const a = areas[area];
    out.push(`## ${area}: ${r.below.length} of ${r.files} files`, "", `Issue #${a.issue}. Closed by ${a.closes}.`, "", "| File | Line | Branch |", "| --- | ---: | ---: |");
    for (const f of [...r.below].sort((x, y) => x.file.localeCompare(y.file))) out.push(`| ${f.file} | ${show(f.line)} | ${show(f.branch)} |`);
    out.push("");
  }
  return out.join("\n");
}

export function spliceTable(doc, table) {
  const s = doc.indexOf(START);
  const e = doc.indexOf(END);
  if (s < 0 || e < s) throw new Error("docs/testing/COVERAGE.md has no coverage-table markers.");
  return `${doc.slice(0, s)}${START}\n\n${table}\n\n${doc.slice(e)}`;
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const t = (p) => join(root, "docs", "testing", p);
  const baseline = JSON.parse(readFileSync(t("coverage-baseline.json"), "utf8"));
  const areas = JSON.parse(readFileSync(t("coverage-areas.json"), "utf8")).areas;
  const { problems } = summarize(baseline, areas);
  if (problems.length > 0) {
    console.error(problems.slice(0, 20).join("\n"));
    process.exit(1);
  }
  const wantDoc = spliceTable(readFileSync(t("COVERAGE.md"), "utf8").split(CR).join(""), renderTable(baseline, areas));
  const wantGaps = renderGaps(baseline, areas);
  if (process.argv.includes("--write")) {
    writeFileSync(t("COVERAGE.md"), wantDoc);
    writeFileSync(t("coverage-gaps.md"), wantGaps);
    console.log("Wrote the coverage table and docs/testing/coverage-gaps.md.");
    return;
  }
  let stale = false;
  const read = (p) => {
    try {
      return readFileSync(p, "utf8").split(CR).join("");
    } catch {
      return "";
    }
  };
  if (read(t("COVERAGE.md")) !== wantDoc) {
    console.error("The per-area table in docs/testing/COVERAGE.md is out of date.");
    stale = true;
  }
  if (read(t("coverage-gaps.md")) !== wantGaps) {
    console.error("docs/testing/coverage-gaps.md is out of date.");
    stale = true;
  }
  if (stale) {
    console.error("Run: node scripts/coverage/coverage-docs.mjs --write");
    process.exit(1);
  }
  console.log("The coverage table and the list of files below 100% match the baseline.");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
