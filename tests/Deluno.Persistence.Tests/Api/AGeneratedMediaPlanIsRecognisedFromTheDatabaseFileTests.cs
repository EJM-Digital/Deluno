using System.Net.Http.Json;
using System.Text.Json;
using Deluno.Persistence.Tests.Support;
using Deluno.Quality.Contracts;
using Deluno.Quality.Scenarios;

namespace Deluno.Persistence.Tests.Api;

/// <summary>
/// A scenario's generated plans are saved through the real route into the real platform database file, read back, and told apart by
/// scenario id and media type (so a scenario's Movie and TV plans never overwrite each other), with the line-based fallback for a plan
/// saved before plans carried the scenario id (#1296).
/// </summary>
public sealed class AGeneratedMediaPlanIsRecognisedFromTheDatabaseFileTests
{
    private static async Task<PolicySetItem[]> ListAsync(ApplicationTestHost app)
        => (await app.Client.GetFromJsonAsync<PolicySetItem[]>("/api/policy-sets", new JsonSerializerOptions(JsonSerializerDefaults.Web)))!;

    [Fact]
    public async Task A_scenarios_movie_and_tv_plans_saved_to_the_database_are_each_found_by_their_own_scenario_and_kind_and_an_older_plan_by_its_marker_line()
    {
        await using var app = await ApplicationTestHost.StartAsync();
        var scenario = MediaPlanScenarioCatalog.All.First(item => item.MediaTypes.Contains("movies", StringComparer.OrdinalIgnoreCase) && item.MediaTypes.Contains("tv", StringComparer.OrdinalIgnoreCase));
        foreach (var kind in new[] { "movies", "tv" })
        {
            var compiled = MediaPlanScenarioCompiler.Compile(scenario.Id, kind, null);
            var saved = await app.Client.PostAsJsonAsync("/api/policy-sets", compiled.PolicySet);
            Assert.True(saved.IsSuccessStatusCode, await saved.Content.ReadAsStringAsync());
        }

        // An older plan: no structured scenario id, only the marker line in its notes.
        var legacy = await app.Client.PostAsJsonAsync("/api/policy-sets", new CreatePolicySetRequest(
            "Old plan", "movies", null, null, null, null, null, true, true, "Scenario: older-scenario v1\nGenerated by Deluno."));
        Assert.True(legacy.IsSuccessStatusCode, await legacy.Content.ReadAsStringAsync());

        // Read back from the platform database file itself, not only from the route's answer.
        using (var connection = new Microsoft.Data.Sqlite.SqliteConnection($"Data Source={Path.Combine(app.DataRoot, "platform.db")};Pooling=False"))
        {
            connection.Open();
            using var count = connection.CreateCommand();
            count.CommandText = "SELECT COUNT(*) FROM policy_sets;";
            Assert.True(Convert.ToInt32(count.ExecuteScalar()) >= 3);
        }

        var plans = await ListAsync(app);
        var movie = Assert.Single(plans, plan => MediaPlanScenarioPlanIdentity.Matches(plan, scenario.Id, "movies"));
        var tv = Assert.Single(plans, plan => MediaPlanScenarioPlanIdentity.Matches(plan, scenario.Id, "tv"));
        Assert.NotEqual(movie.Id, tv.Id);
        Assert.Equal("movies", movie.MediaType);
        Assert.Equal("tv", tv.MediaType);

        var old = Assert.Single(plans, plan => plan.Name == "Old plan");
        Assert.True(MediaPlanScenarioPlanIdentity.Matches(old, "older-scenario", "movies"));
        Assert.False(MediaPlanScenarioPlanIdentity.Matches(old, "older", "movies"));
        Assert.False(MediaPlanScenarioPlanIdentity.Matches(old, "older-scenario", "tv"));
    }
}
